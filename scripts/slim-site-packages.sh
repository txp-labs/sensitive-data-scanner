#!/usr/bin/env bash
# Slim an installed site-packages directory for Lambda: strip debug symbols
# from Linux shared libraries (spaCy's are ~110 MB unstripped) and drop test
# suites that are never imported at run time. Code is otherwise unchanged.
#
#   scripts/slim-site-packages.sh <dir>
set -euo pipefail
dir="${1:?dir}"
if [ "$(uname -s)" = "Linux" ] && command -v strip >/dev/null; then
  find "$dir" -type f \( -name '*.so' -o -name '*.so.*' \) -print0 \
    | xargs -0 -r strip --strip-debug
else
  echo "not stripping: needs Linux binutils" >&2
fi
for pkg in numpy spacy thinc blis srsly preshed cymem murmurhash catalogue weasel confection pyarrow; do
  find "$dir/$pkg" -type d -name tests -prune -exec rm -rf {} + 2>/dev/null || true
done
# pyarrow (container image only): C++ headers, Cython sources, its C++ test
# module, and Arrow Flight (RPC), none of which the scanner imports. Every
# other pyarrow library is linked by the modules it does import.
if [ -d "$dir/pyarrow" ]; then
  rm -rf "$dir/pyarrow/include" "$dir/pyarrow/src"
  find "$dir/pyarrow" -maxdepth 1 -type f \( -name '*.pyx' -o -name '*.pxd' \
    -o -name '_pyarrow_cpp_tests*' -o -name '_flight*' -o -name 'libarrow_flight*' \
    -o -name 'libarrow_python_flight*' -o -name 'flight.py' \) -delete
fi
find "$dir" -name '__pycache__' -prune -exec rm -rf {} +
